/*

### 概要

2つの値の連動を切り替える、Illustrator 標準の［縦横比を固定］風のリンクアイコンの再利用テンプレートです。
onDraw で自作描画し、連動中は縦につながったチェーン、連動していないときは切れたチェーンに斜線を重ねます。
Illustrator・InDesign のどちらでも使えます。

### Overview

A reusable template for a link toggle icon, styled after Illustrator's Constrain Proportions button, that switches whether two values stay linked.
It is custom-drawn in onDraw: a joined chain while linked, and a broken chain with a slash while unlinked.
Works in both Illustrator and InDesign.

*/

