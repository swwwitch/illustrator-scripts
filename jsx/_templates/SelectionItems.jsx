/*

### 概要

選択（グループの中や文字カーソルの選択も含む）から対象のオブジェクトを集め、クリップグループはマスクの形で境界を測る再利用テンプレートです。
テキストフレーム（ポイント／エリア内／パス上）とパスの収集、1件ずつの境界と全体の外接範囲をそろえています。

### Overview

A reusable template that collects target objects from the selection (including items inside groups and a text-cursor selection)
and measures clip groups by the shape of their mask.
It covers collecting text frames (point / area / on a path) and paths, and the bounds of each item and of the whole set.

*/

// =========================================
// 基本情報 / Basic info
// =========================================
var SCRIPT_NAME     = "SelectionItems";               /* スクリプト名 / script name */
var SCRIPT_VERSION  = "v1.0.0";                       /* バージョン / version */
var SCRIPT_AUTHOR   = "Masahiro Takano (@swwwitch)";  /* 作者 / author */
var SCRIPT_RELEASED = "2026-09-28";                   /* 最初のリリース日 / first release date */
var SCRIPT_UPDATED  = "2026-09-28";                   /* 更新日 / last updated */

