/*

### 概要

ダイアログの値を保存・復元する再利用テンプレートです。
保存先は「Illustrator を終了するまで（$.global）」と「再起動しても残す（Folder.userData のファイル）」の2種類から選べ、
どちらも同じ書式（JSON）で読み書きします。読み込むときは既定値と突き合わせ、型の合わない値や知らない項目は捨てます。

### Overview

A reusable template that saves and restores dialog values.
Values live either until Illustrator quits ($.global) or across restarts (a file under Folder.userData);
both use the same format (JSON). On load, values are checked against the defaults, and values of the wrong type
or unknown keys are dropped.

*/

