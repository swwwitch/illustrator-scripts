    /**
     * 入力欄・スライダー・連動アイコンの動作を結び付ける
     * @param {object} dialogControls - ダイアログのコントロール一式
     * @param {function} runPreview - プレビューを掛け直す処理
     * @returns {void}
     */
    function bindValueControls(dialogControls, runPreview) {
        /* 縦の移動距離だけは、ONにしても既定値を入れない / The vertical distance is the one field that keeps its value on enable */
        bindAxisPair(dialogControls.distance, false, runPreview);
        bindAxisPair(dialogControls.scale, true, runPreview);

        var sliderSections = getSliderSections(dialogControls);
        for (var i = 0; i < sliderSections.length; i++) {
            var sliderSection = sliderSections[i];
            bindNumericField(sliderSection.check, sliderSection.field, {
                slider: sliderSection.slider,
                sliderMax: sliderSection.sliderMax,
                fillDefaultOnEnable: true,
                onChange: runPreview
            });
            bindSlider(sliderSection.slider, sliderSection.check, sliderSection.field, runPreview);
        }

        dialogControls.distance.onLinkToggle = function () {
            /* 連動を外したら縦もすぐ使える状態にする / Enable the vertical side as soon as Link is off */
            if (!dialogControls.distance.linkToggle.value) dialogControls.distance.checkY.value = true;
            applyLinkedAxisState(dialogControls.distance);
            /* 連動の切り替えで縦の振れ幅が変わるので、プレビューも掛け直す / The vertical range changes, so refresh the preview */
            runPreview();
        };

        dialogControls.scale.onLinkToggle = function () {
            applyLinkedAxisState(dialogControls.scale);
            runPreview();
        };
    }

    /**
     * 「和文フォントに限定」の有効状態を、フォントの指定に合わせる（オフのときは値も外す）
     * @param {object} fontControls - { randomCheck, japaneseOnlyCheck }
     * @returns {void}
     */
    function updateFontOptionState(fontControls) {
        fontControls.japaneseOnlyCheck.enabled = fontControls.randomCheck.value;
        if (!fontControls.randomCheck.value) fontControls.japaneseOnlyCheck.value = false;
    }

    /**
     * フォントのチェックボックスの動作を結び付ける。
     * ここで移動やスケールは振り直さず、フォントだけを変える
     * @param {object} dialogControls - ダイアログのコントロール一式
     * @param {object} session - プレビューの状態一式
     * @returns {void}
     */
    function bindFontControls(dialogControls, session) {
        var fontControls = dialogControls.font;
        /* テキストが無い選択では使えない / Unavailable when the selection has no text */
        fontControls.randomCheck.enabled = session.textRanges.length > 0;
        fontControls.japaneseOnlyCheck.enabled = false;

        fontControls.randomCheck.onClick = function () {
            updateFontOptionState(fontControls);
            if (!fontControls.randomCheck.value) {
                changeFontsKeepingBase(session, function () { restoreSessionFonts(session); });
                return;
            }
            /* 和文を含む選択では自動でオンにする（欧文フォントでは和文が出ないため）/ Turn on for Japanese text, which Latin fonts cannot show */
            if (containsJapaneseText(session.textRanges) && getJapaneseFonts().length > 0) fontControls.japaneseOnlyCheck.value = true;
            applySelectedFontMode(dialogControls, session);
        };

        fontControls.japaneseOnlyCheck.onClick = function () {
            if (fontControls.japaneseOnlyCheck.value && getJapaneseFonts().length === 0) {
                alert(getLabel("alert.noJapaneseFonts"));
                fontControls.japaneseOnlyCheck.value = false;
                return;
            }
            applySelectedFontMode(dialogControls, session);
        };
    }

